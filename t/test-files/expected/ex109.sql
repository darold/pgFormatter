CREATE FUNCTION f ()
    RETURNS void
    AS $$
DECLARE
    r record;
    c refcursor;
BEGIN
    MOVE NEXT FROM c;
    IF TRUE THEN
        FETCH NEXT FROM c INTO r;
    ELSE
        MOVE LAST FROM c;
    END IF;
    LOOP
        FETCH c INTO r;
        EXIT
        WHEN NOT FOUND;
    END LOOP;
END
$$
LANGUAGE plpgsql;

